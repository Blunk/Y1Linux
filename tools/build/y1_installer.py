"""The Y1 installer in the kernel's built-in initramfs (docs/planning/Y1-RECOVERY-PLAN.md, R4): y1-update-core and
y2-recovery-ui from a Y2ROOT build's Buildroot target, with their loader and libraries, the update
trust and compatibility files and the recovery marker, as a usr/gen_init_cpio list next to
initramfs/y1-production.list. Both images carry it, as the Y2's: PID1's rescue in BOOTIMG runs the core before
the root is mounted (a torn Y2ROOT must not stop it) and the kernel's y2.recovery=1 (RECOVERY's tree) decides
whether it may install. LK's separate ramdisk never reaches this kernel (ATAGs off, appended tree). No e2fsck:
with its five libraries the images left 92 KB of their 6 MiB; PID1 checks Y2DATA's superblock instead
(initramfs/y1-update.h).

    python3 -m tools.build.y1_installer TARGET OUT_DIR
"""
import argparse
import io
from pathlib import Path

from elftools.elf.elffile import ELFFile

from tools.validation.d08 import require

# The programs PID1 runs (initramfs/y1-update.h) and where they sit in the initramfs.
PROGRAMS = {
    'sbin/y1-update-core': 'usr/sbin/y1-update-core',
    'sbin/y2-recovery-ui': 'usr/libexec/y2-recovery-ui',
}
CONFIG = ['etc/y2linux/update-trust.json', 'etc/y2linux/update-compat.json']
# Fixture switches of the host test build; the image's core never carries them.
FIXTURES = [b'Y2_TEST_ROOT', b'Y2_TEST_FAULT']


def needed(target, name, raw, found):
    """name and, depth first, its loader and every DT_NEEDED library, as initramfs path -> source file. A
    library symlink is flattened into its SONAME."""
    found[name] = raw
    elf = ELFFile(io.BytesIO(raw))
    require(elf.elfclass == 32 and elf.little_endian and elf['e_machine'] == 'EM_ARM', 'ARM ELF ' + name)
    for segment in elf.iter_segments():
        if segment['p_type'] == 'PT_INTERP':
            loader = segment.get_interp_name().lstrip('/')
            if loader not in found:
                needed(target, loader, (target / loader).read_bytes(), found)
        if segment['p_type'] == 'PT_DYNAMIC':
            for tag in segment.iter_tags():
                if tag.entry.d_tag != 'DT_NEEDED':
                    continue
                path = next((p for p in (target / 'lib' / tag.needed, target / 'usr/lib' / tag.needed)
                             if p.is_file()), None)
                require(path is not None, 'missing installer library ' + tag.needed)
                library = str(path.relative_to(target))
                if library not in found:
                    needed(target, library, path.read_bytes(), found)


def build(target, out):
    """Writes out/files/<path> and out/y1-installer.list; returns {initramfs path: bytes}."""
    found = {}
    for name, source in PROGRAMS.items():
        raw = (target / source).read_bytes()
        if name == 'sbin/y1-update-core':
            require(not any(f in raw for f in FIXTURES), 'no test fixtures in the installer')
        needed(target, name, raw, found)
    for name in CONFIG:
        found[name] = (target / name).read_bytes()
    found['etc/y2linux/recovery-update'] = b'1\n'
    directories = sorted({'/'.join(name.split('/')[:i]) for name in found for i in range(1, name.count('/') + 1)})
    lines = ['# Generated by tools/build/y1_installer.py from ' + str(target) + '; do not edit.']
    lines += [f'dir /{d} 0755 0 0' for d in directories]
    for name, raw in sorted(found.items()):
        path = out / 'files' / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
        mode = '0644' if name.startswith('etc/') else '0755'
        lines.append(f'file /{name} {path} {mode} 0 0')
    (out / 'y1-installer.list').write_text('\n'.join(lines) + '\n')
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('target', type=Path, help='a Y2ROOT build\'s buildroot/target with y1-update-core')
    parser.add_argument('out', type=Path)
    args = parser.parse_args()
    found = build(args.target, args.out)
    print(f'y1 installer: {len(found)} files, {sum(len(v) for v in found.values())} bytes')


if __name__ == '__main__':
    main()
